#!/usr/bin/env python3
"""Generate the Outliner launcher icon (no dependencies, stdlib only).

Writes, under android/app/src/main/res:
  drawable/ic_launcher_foreground.xml   adaptive-icon foreground (vector)
  values/ic_launcher_background.xml     adaptive-icon background color
  mipmap-*/ic_launcher.png              legacy square icon (API < 26)
  mipmap-*/ic_launcher_round.png        legacy round icon
  drawable/splash_icon.png              splash logo (pre-Android 12)

Motif: three outline rows (bullet + text bar) with an indent guide.
Coordinates use the 108x108 adaptive-icon canvas.
Run: python3 scripts/gen-icons.py   (from apps/android)
"""
import math
import os
import struct
import zlib

BG = (0x2F, 0x8C, 0xF0)
FG = (0xFF, 0xFF, 0xFF)
RES = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'android', 'app', 'src', 'main', 'res')

# (kind, params, alpha)
SHAPES = [
    ('line', (35, 42, 35, 70, 1.6), 0.55),  # indent guide
    ('circle', (35, 36, 5.0), 1.0),
    ('line', (46, 36, 76, 36, 3.2), 1.0),
    ('circle', (47, 54, 4.2), 1.0),
    ('line', (57, 54, 76, 54, 3.0), 1.0),
    ('circle', (47, 70, 4.2), 1.0),
    ('line', (57, 70, 70, 70, 3.0), 1.0),
]


def inside(kind, p, x, y):
    if kind == 'circle':
        cx, cy, r = p
        return (x - cx) ** 2 + (y - cy) ** 2 <= r * r
    x1, y1, x2, y2, r = p  # capsule, r = half stroke width
    dx, dy = x2 - x1, y2 - y1
    t = max(0.0, min(1.0, ((x - x1) * dx + (y - y1) * dy) / (dx * dx + dy * dy)))
    px, py = x1 + t * dx - x, y1 + t * dy - y
    return px * px + py * py <= r * r


def in_mask(mask, u, v):
    # u, v in [0, 1] over the visible square
    if mask == 'circle':
        return (u - 0.5) ** 2 + (v - 0.5) ** 2 <= 0.25
    rad = 0.2
    cu = min(max(u, rad), 1 - rad)
    cv = min(max(v, rad), 1 - rad)
    return (u - cu) ** 2 + (v - cv) ** 2 <= rad * rad


def render(size, mask, crop=(18.0, 90.0), ss=4):
    """Rasterize SHAPES over the BG fill, clipped to `mask`; `crop` is the visible part of the canvas."""
    lo, hi = crop
    n = ss * ss
    bg = tuple(c / 255 for c in BG)
    fg = tuple(c / 255 for c in FG)
    rows = []
    for py in range(size):
        row = bytearray()
        for px in range(size):
            acc = [0.0, 0.0, 0.0]
            cov = 0
            for sy in range(ss):
                for sx in range(ss):
                    u = (px + (sx + 0.5) / ss) / size
                    v = (py + (sy + 0.5) / ss) / size
                    if not in_mask(mask, u, v):
                        continue
                    x, y = lo + u * (hi - lo), lo + v * (hi - lo)
                    col = bg
                    for kind, p, sa in SHAPES:
                        if inside(kind, p, x, y):
                            col = tuple(f * sa + c * (1 - sa) for f, c in zip(fg, col))
                    acc = [a + c for a, c in zip(acc, col)]
                    cov += 1
            if cov:
                row += bytes([round(c / cov * 255) for c in acc] + [round(cov / n * 255)])
            else:
                row += b'\0\0\0\0'
        rows.append(bytes(row))
    return rows


def write_png(path, rows):
    h = len(rows)
    w = len(rows[0]) // 4
    raw = b''.join(b'\0' + r for r in rows)

    def chunk(t, d):
        c = struct.pack('>I', len(d)) + t + d
        return c + struct.pack('>I', zlib.crc32(t + d) & 0xFFFFFFFF)

    data = b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', w, h, 8, 6, 0, 0, 0))
    data += chunk(b'IDAT', zlib.compress(raw, 9)) + chunk(b'IEND', b'')
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'wb') as f:
        f.write(data)


def vector_xml():
    hexfg = '#FF%02X%02X%02X' % FG
    paths = []
    for kind, p, sa in SHAPES:
        alpha = '' if sa == 1.0 else f'\n        android:fillAlpha="{sa}"\n        android:strokeAlpha="{sa}"'
        if kind == 'circle':
            cx, cy, r = p
            d = f'M{cx - r:g},{cy:g}a{r:g},{r:g} 0 1,0 {2 * r:g},0a{r:g},{r:g} 0 1,0 {-2 * r:g},0z'
            paths.append(f'    <path\n        android:fillColor="{hexfg}"{alpha}\n        android:pathData="{d}" />')
        else:
            x1, y1, x2, y2, r = p
            paths.append(
                f'    <path\n        android:strokeColor="{hexfg}"\n        android:strokeWidth="{2 * r:g}"\n'
                f'        android:strokeLineCap="round"{alpha}\n'
                f'        android:pathData="M{x1:g},{y1:g}L{x2:g},{y2:g}" />'
            )
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by scripts/gen-icons.py -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp"\n    android:height="108dp"\n'
        '    android:viewportWidth="108"\n    android:viewportHeight="108">\n'
        + '\n'.join(paths) + '\n</vector>\n'
    )


def main():
    with open(os.path.join(RES, 'drawable', 'ic_launcher_foreground.xml'), 'w') as f:
        f.write(vector_xml())
    with open(os.path.join(RES, 'values', 'ic_launcher_background.xml'), 'w') as f:
        f.write('<?xml version="1.0" encoding="utf-8"?>\n<resources>\n'
                '    <color name="ic_launcher_background">#%02X%02X%02X</color>\n</resources>\n' % BG)
    for dpi, size in (('mdpi', 48), ('hdpi', 72), ('xhdpi', 96), ('xxhdpi', 144), ('xxxhdpi', 192)):
        d = os.path.join(RES, f'mipmap-{dpi}')
        write_png(os.path.join(d, 'ic_launcher.png'), render(size, 'rrect'))
        write_png(os.path.join(d, 'ic_launcher_round.png'), render(size, 'circle'))
    write_png(os.path.join(RES, 'drawable', 'splash_icon.png'), render(288, 'rrect'))


if __name__ == '__main__':
    main()
